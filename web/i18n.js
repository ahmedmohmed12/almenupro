  function current() {
    try {
      return localStorage.getItem(KEY) === 'en' ? 'en' : 'ar';
    } catch (e) {
      return 'ar';
    }
  }

  function t(key) {
    const lang = current();
    return (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.ar[key] || key;
  }

  function apply() {
    const lang = current();
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (key) el.textContent = t(key);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key) el.setAttribute('placeholder', t(key));
    });
    const titleKey = document.documentElement.getAttribute('data-title-key');
    if (titleKey) document.title = t(titleKey);
    const descKey = document.documentElement.getAttribute('data-desc-key');
    const desc = document.querySelector('meta[name="description"]');
    if (desc && descKey) desc.setAttribute('content', t(descKey));
    document.dispatchEvent(new CustomEvent('amp-lang', { detail: { lang } }));
  }

  function toggle() {
    try {
      localStorage.setItem(KEY, current() === 'ar' ? 'en' : 'ar');
    } catch (e) { /* ignore */ }
    apply();
  }

  window.AMP_I18N = { t, apply, toggle, current };

  document.addEventListener('click', (event) => {
    if (event.target.closest('.lang-toggle')) {
      event.preventDefault();
      toggle();
    }
  });

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', apply);
  } else {
    apply();
  }
